// Writes lib/firebase_options.dart for the web build, the way
// `flutterfire configure` would, but without an interactive login: it uses the
// Firebase CLI with whatever credentials GOOGLE_APPLICATION_CREDENTIALS points
// at, so the deploy workflow can run it.
//
// Creates the project's web app first if it does not have one yet.
//
//   node tool/write_firebase_options.mjs <project-id>

import {execFileSync} from "node:child_process";
import {writeFileSync} from "node:fs";

const project = process.argv[2];
if (!project) {
  console.error("Usage: node tool/write_firebase_options.mjs <project-id>");
  process.exit(1);
}

function firebase(...args) {
  const out = execFileSync("npx",
      ["--yes", "firebase-tools@14", ...args, "--project", project, "--json"],
      {encoding: "utf8", stdio: ["ignore", "pipe", "inherit"]});
  const json = JSON.parse(out);
  if (json.status !== "success") {
    throw new Error(`firebase ${args.join(" ")}: ${out}`);
  }
  return json.result;
}

let apps = firebase("apps:list", "WEB");
if (!apps?.length) {
  console.log("No web app in this project yet, creating one.");
  firebase("apps:create", "WEB", "Red Flag");
  apps = firebase("apps:list", "WEB");
}
const appId = apps[0].appId;
const result = firebase("apps:sdkconfig", "WEB", appId);
// Newer CLIs return the config as an object, older ones only as JS source.
function parseConfig(source) {
  const body = source.match(/\{[\s\S]*\}/)[0];
  try {
    return JSON.parse(body);
  } catch {
    return JSON.parse(body.replace(/^(\s*)(\w+):/gm, "$1\"$2\":"));
  }
}
const config = result.sdkConfig ?? parseConfig(result.fileContents);

const field = (dartName, key) =>
  config[key] ? `    ${dartName}: '${config[key]}',\n` : "";

writeFileSync("lib/firebase_options.dart", `// Generated by tool/write_firebase_options.mjs for project ${project}.
// Do not edit by hand; the deploy workflow rewrites it on every run.

import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;
import 'package:flutter/foundation.dart' show kIsWeb;

class DefaultFirebaseOptions {
  static FirebaseOptions get currentPlatform {
    if (kIsWeb) return web;
    throw UnsupportedError(
      'Für Android und iOS \`flutterfire configure\` ausführen.',
    );
  }

  static const FirebaseOptions web = FirebaseOptions(
${field("apiKey", "apiKey")}${field("appId", "appId")}${field("messagingSenderId", "messagingSenderId")}${field("projectId", "projectId")}${field("authDomain", "authDomain")}${field("storageBucket", "storageBucket")}${field("measurementId", "measurementId")}  );
}
`);
console.log(`Wrote lib/firebase_options.dart for ${project} (${appId}).`);
